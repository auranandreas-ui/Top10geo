function normalize(s){
  return s.toLowerCase()
    .normalize("NFD").replace(/[̀-ͯ]/g,"")
    .replace(/^\s*the\s+/,"")
    .replace(/[^a-z0-9]/g,"");
}
function buildAliasSet(answerName){
  const set = new Set();
  set.add(normalize(answerName));
  const key = answerName.toLowerCase();
  if(ALIASES[key]){
    ALIASES[key].forEach(a => set.add(normalize(a)));
  }
  return set;
}

// Strips the answer key out of a question — safe to send to the client.
function toPublicQuestion(q){
  return {
    id: q.id,
    difficulty: q.difficulty,
    ranked: q.ranked,
    icon: q.icon,
    topic: q.topic || "geography",
    continent: q.continent || null,
    title: q.title,
    prompt: q.prompt,
    fact: q.fact,
    total: q.answers.length
  };
}

function getPublicQuestions(){
  return QUESTIONS.map(toPublicQuestion);
}

function getQuestionById(id){
  return QUESTIONS.find(q => q.id === Number(id));
}

// Checks one guess against one question's answer key server-side.
// Returns { matchedIndex, canonicalAnswer } or { matchedIndex: -1 }.
function checkGuess(question, rawGuess, alreadyFoundIndexes){
  const norm = normalize(rawGuess || "");
  if(!norm) return { matchedIndex: -1 };
  for(let i = 0; i < question.answers.length; i++){
    if(alreadyFoundIndexes && alreadyFoundIndexes.includes(i)) continue;
    const set = buildAliasSet(question.answers[i]);
    if(set.has(norm)) return { matchedIndex: i, canonicalAnswer: question.answers[i] };
  }
  return { matchedIndex: -1 };
}

